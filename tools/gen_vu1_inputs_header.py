#!/usr/bin/env python3
"""Writes app/setup/vu1lift/vu1_inputs.h from tools/disc_vu_inputs.py and the target list and fixed text blocks of
tools/vu1_translator.py (issue 011: the C++ VU1 lifter uses the same tables). Offsets, sizes and checksums only,
never instruction bytes. Run after changing either Python file; the C++ output must stay byte-identical."""
import ast, os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import disc_vu_inputs as d

# The translator's target list lives in its __main__ block; read it without running the translation.
src = open(os.path.join(here, 'vu1_translator.py')).read()
targets_expr = src[src.index('    targets = [') + len('    targets = '):src.index('\n\n    out = []')]
targets = eval(targets_expr, {})

out = ['#pragma once',
       '// Generated by tools/gen_vu1_inputs_header.py from tools/disc_vu_inputs.py and tools/vu1_translator.py.',
       '// Where the lifted VU1 programs sit in the player\'s own executable: offsets, sizes and checksums only.',
       '#include <cstdint>', '', 'namespace dw5xl::vu1lift {', '',
       'struct Chunk', '{', '    uint32_t pc, offset, size;', '    const char *source; // nullptr: the executable', '};',
       'struct Range', '{', '    const char *key;', '    uint32_t start, end;', '    const char *name;',
       '    const Chunk *chunks;', '    uint32_t chunkCount;', '    const char *sha256;', '};',
       'struct ImageRegistration', '{', '    uint64_t hash;', '    uint32_t pc;', '    const char *name;', '};',
       'struct Target', '{', '    const char *key;', '    uint32_t pc, end;', '    const char *name;', '};',
       'struct SourceFile', '{', '    const char *name;', '    const char *sha256;', '};', '',
       f'inline constexpr const char *kElfSha256 = "{d.ELF_SHA256}";', '']
out.append('inline constexpr SourceFile kSourceFiles[] = {')
for name, sha in d.SOURCE_SHA256.items():
    out.append(f'    {{"{name}", "{sha}"}},')
out.append('};')
for i, (key, start, end, name, chunks, digest) in enumerate(d.RANGES):
    items = []
    for c in chunks:
        source = f'"{c[3]}"' if len(c) > 3 else 'nullptr'
        items.append(f'{{{c[0]}u, {c[1]}u, {c[2]}u, {source}}}')
    out.append(f'inline constexpr Chunk kChunks{i}[] = {{{", ".join(items)}}};')
out.append('inline constexpr Range kRanges[] = {')
for i, (key, start, end, name, chunks, digest) in enumerate(d.RANGES):
    out.append(f'    {{"{key}", {start}u, {end}u, "{name}", kChunks{i}, {len(chunks)}u, "{digest}"}},')
out.append('};')
out.append('inline constexpr ImageRegistration kImageRegistrations[] = {')
for h, pc, name in d.IMAGE_REGISTRATIONS:
    out.append(f'    {{0x{h:016x}ull, {pc}u, "{name}"}},')
out.append('};')
out.append('inline constexpr Target kTargets[] = {')
for key, pc, end, name in targets:
    out.append(f'    {{"{key}", {pc}u, {end}u, "{name}"}},')
out.append('};')
# VU0 microprograms (issue 025): the same tables for tools/vu0_translator.py.
for i, (key, start, end, name, chunks, digest) in enumerate(d.VU0_RANGES):
    items = [f'{{{c[0]}u, {c[1]}u, {c[2]}u, {chr(34) + c[3] + chr(34) if len(c) > 3 else "nullptr"}}}' for c in chunks]
    out.append(f'inline constexpr Chunk kVu0Chunks{i}[] = {{{", ".join(items)}}};')
out.append('inline constexpr Range kVu0Ranges[] = {')
for i, (key, start, end, name, chunks, digest) in enumerate(d.VU0_RANGES):
    out.append(f'    {{"{key}", {start}u, {end}u, "{name}", kVu0Chunks{i}, {len(chunks)}u, "{digest}"}},')
out.append('};')
# The fixed C++ text the translator writes before the segments (LIFT_PREAMBLE, shared with the VU0 output) and
# after them (the flush functions), verbatim.
blocks = []
start = src.index('LIFT_PREAMBLE = """') + len('LIFT_PREAMBLE = """')
blocks.append(src[start:src.index('"""', start)])
start = src.index('out.append("""') + len('out.append("""')
blocks.append(src[start:src.index('""")', start)])
for name, text in zip(('kPrologue', 'kFlushFunctions'), blocks):
    if ')DW5XL"' in text:
        raise SystemExit('raw string delimiter appears in the block')
    out.append(f'inline constexpr const char *{name} = R"DW5XL({text})DW5XL";')
out += ['', '} // namespace dw5xl::vu1lift', '']
path = os.path.join(here, '..', 'app', 'setup', 'vu1lift', 'vu1_inputs.h')
os.makedirs(os.path.dirname(path), exist_ok=True)
open(path, 'w').write('\n'.join(out))
print(f'wrote {os.path.normpath(path)}: {len(d.RANGES)} ranges, {len(d.IMAGE_REGISTRATIONS)} registrations, '
      f'{len(targets)} targets')
